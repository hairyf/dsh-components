#!/usr/bin/env node
/**
 * Generate src/theme/styles.ts from the recovered official stylesheets.
 *
 * The CSS text has to survive verbatim, so it is embedded as a template
 * literal with backticks and interpolation markers escaped. Everything else
 * in the module is ordinary TypeScript.
 *
 * Run: node scripts/generate-theme.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE_DIR = join(ROOT, 'docs', 'reference', 'extracted', 'theme', 'css')
const TARGET = join(ROOT, 'src', 'theme', 'styles.ts')

/** Sheets to embed, in cascade order, with the description each one gets. */
const SHEETS = [
  ['DESIGN_PLATFORM_CSS', 'design-platform.css', 'Design tokens: static palette, alias roles, light and dark bodies.'],
  ['GRADIENT_SHADOW_TEXT_CSS', 'gradient-shadow-text.css', 'Typography scale and gradient/shadow text treatments, including the font tokens.'],
  ['BASE_CSS', 'base.css', 'Document baseline: radius, transition durations, font families.'],
  ['FOCUS_CSS', 'focus.css', 'Focus-ring presentation shared by every interactive atom.'],
  ['SCROLLBAR_CSS', 'scrollbar.css', 'Scrollbar skin for scrollable surfaces.'],
  ['CORNER_SHAPE_CSS', 'corner-shape.css', 'Superellipse corner-shape opt-in for supported engines.'],
  ['ONBOARDING_CSS', 'onboarding.css', 'First-run onboarding presentation.'],
  ['SHIKI_CSS', 'shiki.css', 'Syntax-highlighting token colors used by code surfaces.'],
]

const BACKSLASH = String.fromCharCode(92)
const BACKTICK = String.fromCharCode(96)
const DOLLAR = String.fromCharCode(36)

/**
 * Escape a stylesheet so it can sit inside a template literal.
 * @param css - the raw stylesheet.
 */
function toTemplateLiteral(css) {
  return css
    .split(BACKSLASH)
    .join(BACKSLASH + BACKSLASH)
    .split(BACKTICK)
    .join(BACKSLASH + BACKTICK)
    .split(`${DOLLAR}{`)
    .join(`${BACKSLASH + DOLLAR}{`)
}

const chunks = [
  '/**',
  ' * Document-level stylesheets recovered verbatim from the official theme package.',
  ' * Generated by scripts/generate-theme.mjs. Do not edit by hand.',
  ' */',
  '',
]

const seen = new Set()
for (const [name, file, description] of SHEETS) {
  const source = join(SOURCE_DIR, file)
  if (!existsSync(source)) {
    console.error(`missing recovered sheet: ${file}`)
    process.exit(1)
  }
  const css = readFileSync(source, 'utf8').trim()
  for (const match of css.matchAll(/--((?:dsw|dsh|ds)-[a-z0-9-]+)\s*:/g))
    seen.add(match[1])
  chunks.push(`/** ${description} */`)
  chunks.push(`export const ${name} = ${BACKTICK}${toTemplateLiteral(css)}${BACKTICK}`)
  chunks.push('')
}

writeFileSync(TARGET, chunks.join('\n'))
console.log(`wrote src/theme/styles.ts with ${SHEETS.length} sheets, ${seen.size} distinct tokens`)
