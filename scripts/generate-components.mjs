/**
 * Generate the component barrel and the official-surface re-export.
 *
 * Two facts drive this script:
 *
 * 1. Every recovered component lives one-per-file under src/components/<group>/,
 *    so the barrel is generated from the tree instead of being hand-maintained.
 * 2. The library forks a large part of @deepseek-ai/dsh-client-ui-primitives.
 *    A bare re-export of both would make 61 names ambiguous, so the official
 *    surface is re-exported explicitly, minus everything this library ships
 *    itself. The icons in particular pass straight through: they are official
 *    artwork that a refork would only make worse.
 *
 * The same scan feeds docs/reference/components.json and the generated skills.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const COMPONENTS = join(ROOT, 'src/components')
const PRIMITIVES = join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-primitives/lib/types/index.d.ts')
/** The runtime bundle, which is where the Icon* values actually live. */
const PRIMITIVES_RUNTIME = join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-primitives/lib/index.js')

/** Preferred export order; any other directory is appended alphabetically. */
const PREFERRED_ORDER = [
  'primitives',
  'layout',
  'settings',
  'feedback',
  'media',
  'content',
  'viewer',
]

/**
 * Read the exported symbols of a module, with their JSDoc summary when present.
 * @param source - the module's source text.
 */
function readExports(source) {
  const out = []
  // Every exported kind counts: a fork that shadows a value but not its type
  // would still leave the upstream type reachable, which is a naming conflict.
  const pattern = /(?:\/\*\*([\s\S]*?)\*\/\s*)?export (?:declare )?(?:function|const|class|interface|type|enum) (\w+)/g
  for (const match of source.matchAll(pattern)) {
    const doc = match[1] ?? ''
    const summary = doc
      .split('\n')
      .map(line => line.replace(/^\s*\*\s?/, '').trim())
      .filter(line => line && !line.startsWith('@'))
      .join(' ')
    out.push({ name: match[2], summary })
  }
  return out
}

/**
 * Read every name the primitives package exports, split into values and types.
 * @param source - the package's index.d.ts.
 */
function readPrimitiveExports(source) {
  const values = new Set()
  const types = new Set()
  for (const block of source.matchAll(/export (type )?\{([^}]+)\}/g)) {
    const blockIsTypeOnly = Boolean(block[1])
    for (const raw of block[2].split(',')) {
      const entry = raw.trim()
      if (!entry)
        continue
      const inlineType = entry.startsWith('type ')
      const name = entry
        .replace(/^type\s+/, '')
        .replace(/\s+as\s+(?:\S.*)?$/, '')
        .trim()
      if (!name)
        continue
      if (blockIsTypeOnly || inlineType)
        types.add(name)
      else
        values.add(name)
    }
  }
  for (const name of values)
    types.delete(name)
  return {
    values: [...values].sort(),
    types: [...types].sort(),
  }
}

const groups = readdirSync(COMPONENTS, { withFileTypes: true })
  .filter(entry => entry.isDirectory())
  .map(entry => entry.name)
  // `internal` holds helpers that back a public component but are not one.
  .filter(name => name !== 'internal')
  .sort((a, b) => {
    const ai = PREFERRED_ORDER.indexOf(a)
    const bi = PREFERRED_ORDER.indexOf(b)
    // Known groups keep their order; unknown ones follow alphabetically, so a
    // new directory is picked up instead of being silently skipped.
    if (ai === -1 && bi === -1)
      return a.localeCompare(b)
    if (ai === -1)
      return 1
    if (bi === -1)
      return -1
    return ai - bi
  })

const barrel = [
  '/**',
  ' * Every recovered component, in one barrel.',
  ' *',
  ' * Generated by scripts/generate-components.mjs. Do not edit by hand.',
  ' */',
  '',
]
const inventory = []
const ourNames = new Set()

for (const group of groups) {
  const dir = join(COMPONENTS, group)
  const files = readdirSync(dir).filter(name => name.endsWith('.tsx')).sort()
  barrel.push(`// ${group}`)
  for (const file of files) {
    barrel.push(`export * from './${group}/${file.replace(/\.tsx$/, '')}'`)
    const source = readFileSync(join(dir, file), 'utf8')
    const exports = readExports(source)
    for (const entry of exports) ourNames.add(entry.name)
    if (exports.length > 0)
      inventory.push({ group, file: `src/components/${group}/${file}`, exports })
  }
  barrel.push('')
}
barrel.push('// Official primitives: the icons and the components this library does not')
barrel.push('// refork, re-exported so a plugin has one import for both.')
barrel.push('export * from \'./official\'')
barrel.push('')
// sort-exports wants the specifiers ascending regardless of group order, and
// writing them sorted keeps the generated file lint-clean without a --fix pass.
const header = barrel.filter(line => line.startsWith('/**') || line.startsWith(' *'))
const pathOf = line => /\.\/([^']+)'/.exec(line)?.[1] ?? ''
const exportsOnly = barrel
  .filter(line => line.startsWith('export '))
  // Plain code-unit comparison on the module path: the lint rule orders
  // `text` before `text-shimmer`, which a locale collation gets backwards.
  .sort((a, b) => pathOf(a).localeCompare(pathOf(b), 'en', { sensitivity: 'variant', numeric: true }))
const output = [
  ...header,
  '',
  ...exportsOnly,
  '',
]
writeFileSync(join(COMPONENTS, 'index.ts'), output.join('\n'))

const runtimeValues = readPrimitiveExports(readFileSync(PRIMITIVES_RUNTIME, 'utf8')).values
const declared = readPrimitiveExports(readFileSync(PRIMITIVES, 'utf8'))
// Values: the runtime bundle is authoritative (the .d.ts omits every Icon*).
// Types: only the declaration file knows them.
const primitives = { values: runtimeValues, types: declared.types }
const natural = (a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' })
const keptValues = primitives.values.filter(name => !ourNames.has(name)).sort(natural)
const keptTypes = primitives.types.filter(name => !ourNames.has(name)).sort(natural)
const forked = [
  ...primitives.values,
  ...primitives.types,
].filter(name => ourNames.has(name)).sort()

const official = [
  '/**',
  ' * The part of the official primitives surface this library does not refork.',
  ' *',
  ' * Generated by scripts/generate-components.mjs. Do not edit by hand.',
  ' *',
  ' * Names this library ships itself are listed in forkedNames and are',
  ' * deliberately absent here: src/index.ts exports them from ./components, so',
  ' * an import always resolves to the refork rather than the upstream atom.',
  ' * The Icon* artwork is not forked and passes through unchanged.',
  ' */',
  '',
]

const VALUE_CHUNK = 6
for (let i = 0; i < keptValues.length; i += VALUE_CHUNK)
  official.push(`export { ${keptValues.slice(i, i + VALUE_CHUNK).join(', ')} } from '@deepseek-ai/dsh-client-ui-primitives'`)
official.push('')
const TYPE_CHUNK = 6
for (let i = 0; i < keptTypes.length; i += TYPE_CHUNK)
  official.push(`export type { ${keptTypes.slice(i, i + TYPE_CHUNK).join(', ')} } from '@deepseek-ai/dsh-client-ui-primitives'`)
official.push('')
official.push('/** Names the library reforked, so they are not re-exported from upstream. */')
official.push('export const forkedNames = [')
for (const name of forked)
  official.push(`  '${name}',`)
official.push('] as const')
official.push('')
writeFileSync(join(COMPONENTS, 'official.ts'), official.join('\n'))

mkdirSync(join(ROOT, 'docs/reference'), { recursive: true })
writeFileSync(join(ROOT, 'docs/reference/components.json'), `${JSON.stringify({
  groups,
  modules: inventory,
  forked,
  upstream: { values: keptValues.length, types: keptTypes.length },
}, null, 2)}\n`)

console.log('component files:', inventory.length, '| symbols:', ourNames.size)
console.log('upstream re-exported:', keptValues.length, 'values,', keptTypes.length, 'types')
console.log('forked (shadowed):', forked.length)
